#!/usr/bin/env python
"""Derive a stage-2 task config from the stage-1 teacher recipe it must match.

Distillation reuses the teacher's physical task verbatim -- preflight compares
scene, action, command, event, reward and termination options and refuses a
mismatch -- so the student config is the recipe with two deltas:

- ``tactile_sensors`` restored to the student observation group, which the
  recipes drop because their own students are proprioception-only;
- ``runner_options.actor`` and ``runner_options.algorithm`` removed, since both
  carry PPO exploration knobs that ``RslRlDistillationAlgorithmOptions`` rejects.
"""

import argparse
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
STUDENT_GROUP = ["proprio", "goal", "tactile_sensors"]
HEADER = "# Generated by scripts/make_distill_config.py from {source}. Do not edit by hand.\n"


def derive(recipe: dict) -> dict:
    out = {key: value for key, value in recipe.items()}
    runner = {key: value for key, value in out.get("runner_options", {}).items()}
    for key in ("actor", "algorithm"):
        runner.pop(key, None)
    runner.setdefault("obs_groups", {})
    runner["obs_groups"] = {**runner["obs_groups"], "student": list(STUDENT_GROUP)}
    out["runner_options"] = runner
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("recipes", nargs="+", type=Path)
    parser.add_argument("--check", action="store_true", help="Fail if any output is missing or stale")
    args = parser.parse_args()
    stale = []
    for recipe in args.recipes:
        target = recipe.with_name(recipe.stem + "_distill.yaml")
        # Repo-relative, so the header matches however the recipe was addressed.
        source = recipe.resolve().relative_to(ROOT).as_posix()
        body = HEADER.format(source=source) + yaml.safe_dump(
            derive(yaml.safe_load(recipe.read_text())), sort_keys=False
        )
        if args.check:
            if not target.exists() or target.read_text() != body:
                stale.append(target)
            continue
        target.write_text(body)
        print(target)
    if stale:
        raise SystemExit("Stale or missing: " + ", ".join(p.as_posix() for p in stale))


if __name__ == "__main__":
    main()
