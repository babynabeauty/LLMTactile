#!/usr/bin/env python
"""Inject the interactive ablation charts into the project page.

The data is embedded rather than fetched: anonymous.4open.science serves every file
under a CSP sandbox with no allow-same-origin and sends no CORS headers, so a page
there cannot fetch its own JSON. Everything the charts need therefore ships inside
``index.html``, between the markers this script owns.
"""

import argparse
import json
from pathlib import Path

BEGIN = "  <!-- BEGIN ablation-widget (generated by scripts/build_ablation_widget.py) -->"
END = "  <!-- END ablation-widget -->"

AXIS_LABEL = {
    "in_hand_repose": "Goals reached per episode",
    "in_fingers_rotate": "Total rotation (turns)",
    "grasp_lift": "Objects carried (of 17)",
}
PAIR_TITLE = {
    "in_hand_repose-wuji": "In-hand repose · Wuji",
    "in_fingers_rotate-sharpa": "In-fingers rotate · Sharpa",
    "grasp_lift-allegro": "Grasp and lift · Allegro",
}
TYPE_ORDER = ["agg_bool", "bool", "agg_force", "force",
              "force_torque", "depth", "proximity", "elastomer"]
# Trained and collected, but out of the study: a per-link reading is one vector for a whole
# finger segment, which is a different kind of device from the taxel arrays being compared.
EXCLUDED_TYPES = {"link_bool", "link_force"}
# One slot per entry of TYPE_ORDER. Stepped for a light surface and checked for
# adjacent-pair separation under protan, deutan and tritan simulation; the three
# lightest slots sit under 3:1 contrast, which the widget's table view covers.
TYPE_COLOR = {
    "agg_bool": "#2a78d6", "bool": "#eb6834",
    "agg_force": "#1baf7a", "force": "#eda100",
    "force_torque": "#e87ba4", "depth": "#008300", "proximity": "#4a3aa7",
    "elastomer": "#e34948",
}


def payload(results, teachers, final_iteration=None):
    runs = results["runs"]
    if final_iteration is not None:
        runs = [{**r, "series": {k: [pt for pt in v if pt[0] <= final_iteration]
                                 for k, v in r.get("series", {}).items()}}
                for r in runs if studied(r) and scored_at(r, final_iteration)]
    pairs = []
    for pair, title in PAIR_TITLE.items():
        task, robot = pair.rsplit("-", 1)
        subset = [r for r in runs if r["task"] == task and r["robot"] == robot]
        if not subset:
            continue
        by_type, by_level = [], []
        for name in TYPE_ORDER:
            run = next((r for r in subset if r["modality"] == name and r["imperfection"] == "clean"), None)
            series = (run or {}).get("series", {}).get("clean") or []
            if series:
                by_type.append({"name": name, "final": series[-1][1], "series": series})
        for level in ("clean", "mild", "strong"):
            run = next((r for r in subset if r["modality"] == "force_torque" and r["imperfection"] == level), None)
            series = (run or {}).get("series", {}).get("clean") or []
            if series:
                by_level.append({"name": level, "final": series[-1][1], "series": series})
        base = next((r for r in subset if r["modality"] == "none"), None)
        pairs.append({
            "id": pair,
            "title": title,
            "axis": AXIS_LABEL[task],
            "teacher": teachers.get(pair),
            "baseline": ((base or {}).get("series", {}).get("clean") or [[0, None]])[-1][1],
            "baselineSeries": (base or {}).get("series", {}).get("clean") or [],
            "types": by_type,
            "levels": by_level,
        })
    return {"pairs": pairs}


def checkpoints_through(final_iteration):
    """Every checkpoint a run should have been scored at, ending at ``final_iteration``.

    Checkpoints land every 500 updates, and a budget of N updates writes its last one at N-1,
    so 2999 closes the 3000-update ladder while 2500 is a checkpoint in its own right.
    """
    ladder = list(range(500, final_iteration + 1, 500))
    if final_iteration not in ladder:
        ladder.append(final_iteration)
    return ladder


def studied(run):
    """Whether this run is one of the cells the figures compare."""
    return run.get("modality") not in EXCLUDED_TYPES


def scored_at(run, iteration):
    """Whether this run has a clean evaluation at ``iteration``.

    Membership is read from the evaluations themselves rather than from ``last_iteration``,
    which a run only records once it finishes: a still-training cell has a usable checkpoint
    at 2500 long before it can claim one.
    """
    return any(point[0] == iteration for point in run.get("series", {}).get("clean", []))


def require_complete_matrix(results, final_iteration):
    """Reject publication input unless every intended ablation cell is final."""
    final_runs = [run for run in results["runs"] if studied(run) and scored_at(run, final_iteration)]
    expected = {
        (pair, modality, "clean")
        for pair in PAIR_TITLE
        for modality in ["none", *TYPE_ORDER]
    }
    expected.update(
        (pair, "force_torque", level)
        for pair in PAIR_TITLE
        for level in ("mild", "strong")
    )
    observed = {
        (f'{run["task"]}-{run["robot"]}', run["modality"], run["imperfection"])
        for run in final_runs
    }
    missing = sorted(expected - observed)
    unexpected = sorted(observed - expected)
    duplicate = sorted(
        key for key in expected
        if sum(
            (f'{run["task"]}-{run["robot"]}', run["modality"], run["imperfection"]) == key
            for run in final_runs
        ) > 1
    )
    bad_series = []
    for run in final_runs:
        key = (f'{run["task"]}-{run["robot"]}', run["modality"], run["imperfection"])
        if key not in expected:
            continue
        iterations = [point[0] for point in run.get("series", {}).get("clean", [])
                      if point[0] <= final_iteration]
        if iterations != checkpoints_through(final_iteration):
            bad_series.append((key, iterations))
    if missing or unexpected or duplicate or bad_series:
        details = []
        if missing:
            details.append("missing=" + ", ".join("/".join(cell) for cell in missing))
        if unexpected:
            details.append("unexpected=" + ", ".join("/".join(cell) for cell in unexpected))
        if duplicate:
            details.append("non-unique=" + ", ".join("/".join(cell) for cell in duplicate))
        if bad_series:
            details.append("bad-series=" + ", ".join(
                "/".join(key) + f":{iterations}" for key, iterations in bad_series
            ))
        raise ValueError(
            f"publication matrix is incomplete at iteration {final_iteration}: "
            + "; ".join(details)
        )


SECTION = """  <!-- BEGIN ablation-widget (generated by scripts/build_ablation_widget.py) -->
  <section class="section section--alt">
    <div class="container">
      <h2>Representation and Imperfection Curves</h2>
      <p class="abl__intro">
        Every tactile student is distilled from the same privileged teacher for its hand and task, so the only thing
        that changes across a curve is what the student can feel. Both views show checkpoint performance over
        distillation iterations: settled-goal success for repose and lift, and retained axial speed for continuous
        rotation. The first compares tactile types; the second holds the type at <code>force_torque</code> and varies
        the sensor imperfection profile. Wuji <code>elastomer</code> uses 250 internal surface-query samples instead
        of the default 500, without changing its taxel layout or observation dimension. Pick a task, hover a mark for
        its value, or show the table. Lift is scored here over the 17 training objects, so these curves sit on a
        different scale from the paper's 50-unseen-variant panel.
      </p>
      <div class="abl" data-ablations='__DATA__'>
        <div class="abl__controls">
          <div class="abl__group" role="tablist" aria-label="Ablation">
            <button class="abl__tab" type="button" role="tab" aria-selected="true" data-view="types">By tactile type</button>
            <button class="abl__tab" type="button" role="tab" aria-selected="false" data-view="levels">By imperfection</button>
          </div>
          <div class="abl__group abl__group--pairs" role="tablist" aria-label="Task"></div>
          <button class="abl__toggle" type="button" aria-pressed="false">Show table</button>
        </div>
        <figure class="abl__figure">
          <div class="abl__plot"></div>
          <figcaption class="abl__caption"></figcaption>
        </figure>
        <div class="abl__table" hidden></div>
      </div>
    </div>
  </section>

  <script>
    (function () {
      const root = document.querySelector('.abl');
      if (!root) return;
      const data = JSON.parse(root.dataset.ablations);
      if (!data.pairs.length) return;
      const plot = root.querySelector('.abl__plot');
      const caption = root.querySelector('.abl__caption');
      const tableBox = root.querySelector('.abl__table');
      const pairBar = root.querySelector('.abl__group--pairs');
      const toggle = root.querySelector('.abl__toggle');
      const NS = 'http://www.w3.org/2000/svg';
      let view = 'types';
      let pairId = data.pairs[0].id;

      data.pairs.forEach(function (pair, i) {
        const b = document.createElement('button');
        b.className = 'abl__tab';
        b.type = 'button';
        b.setAttribute('role', 'tab');
        b.setAttribute('aria-selected', String(i === 0));
        b.dataset.pair = pair.id;
        b.textContent = pair.title;
        pairBar.appendChild(b);
      });

      const fmt = function (v) { return v === null || v === undefined ? '\\u2014' : (+v).toFixed(3); };
      const el = function (name, attrs) {
        const node = document.createElementNS(NS, name);
        for (const k in attrs) node.setAttribute(k, attrs[k]);
        return node;
      };

      function current() { return data.pairs.find(function (p) { return p.id === pairId; }); }

      function drawTypes(pair, svg, W, H, pad) {
        const series = pair.types.map(function (s) {
          return { name: s.name, points: s.series, color: __TYPE_COLORS__[s.name] };
        });
        if (pair.baselineSeries.length) series.push({ name: 'no tactile', points: pair.baselineSeries, cls: 'abl-line--base' });
        drawSeries(pair, series, svg, W, H, pad);
      }

      function drawSeries(pair, series, svg, W, H, pad) {
        if (!series.length) return;
        let xs = [], ys = [];
        series.forEach(function (s) { s.points.forEach(function (p) { xs.push(p[0]); ys.push(p[1]); }); });
        if (pair.teacher !== null && pair.teacher !== undefined) ys.push(pair.teacher);
        const x0 = Math.min.apply(null, xs), x1 = Math.max.apply(null, xs);
        let lo = Math.min.apply(null, ys), hi = Math.max.apply(null, ys);
        const span = (hi - lo) || 1;
        lo -= span * 0.1; hi += span * 0.1;
        const X = function (v) { return pad.l + (v - x0) / ((x1 - x0) || 1) * (W - pad.l - pad.r); };
        const Y = function (v) { return H - pad.b - (v - lo) / (hi - lo) * (H - pad.t - pad.b); };
        const yTicks = [lo, (lo + hi) / 2, hi];
        yTicks.forEach(function (v) {
          svg.appendChild(el('line', { x1: pad.l, x2: W - pad.r, y1: Y(v), y2: Y(v), class: 'abl-grid' }));
        });
        if (pair.teacher !== null && pair.teacher !== undefined) svg.appendChild(el('line', { x1: pad.l, x2: W - pad.r, y1: Y(pair.teacher), y2: Y(pair.teacher), class: 'abl-ref abl-ref--teacher' }));
        series.forEach(function (s) {
          const d = s.points.map(function (p, i) { return (i ? 'L' : 'M') + X(p[0]) + ' ' + Y(p[1]); }).join(' ');
          const attrs = { d: d, class: 'abl-line ' + (s.cls || '') };
          if (s.color) attrs.style = 'stroke:' + s.color;
          svg.appendChild(el('path', attrs));
          s.points.forEach(function (p) {
            const dotAttrs = { cx: X(p[0]), cy: Y(p[1]), r: 4, class: 'abl-point ' + (s.cls || '') };
            if (s.color) dotAttrs.style = 'stroke:' + s.color + ';fill:' + s.color;
            const dot = el('circle', dotAttrs);
            dot.appendChild(el('title')).textContent = s.name + ' @ ' + p[0] + ': ' + fmt(p[1]);
            svg.appendChild(dot);
          });
        });
        yTicks.forEach(function (v) {
          const t = el('text', { x: pad.l - 10, y: Y(v) + 4, class: 'abl-ylabel' });
          t.textContent = (+v).toFixed(2);
          svg.appendChild(t);
        });
        [x0, x1].forEach(function (v) {
          const t = el('text', { x: X(v), y: H - pad.b + 18, class: 'abl-xtick' });
          t.textContent = v;
          svg.appendChild(t);
        });
        const at = el('text', { x: (pad.l + W - pad.r) / 2, y: H - 4, class: 'abl-axis' });
        at.textContent = 'Distillation iteration';
        svg.appendChild(at);
        const yt = el('text', { x: 14, y: H / 2, class: 'abl-axis', transform: 'rotate(-90 14 ' + (H / 2) + ')' });
        yt.textContent = pair.axis;
        svg.appendChild(yt);
      }

      function drawLevels(pair, svg, W, H, pad) {
        const series = pair.levels.map(function (s) { return { name: s.name, points: s.series, cls: 'abl-line--' + s.name }; });
        if (pair.baselineSeries.length) series.push({ name: 'no tactile', points: pair.baselineSeries, cls: 'abl-line--base' });
        drawSeries(pair, series, svg, W, H, pad);
      }

      function legend(pair) {
        const items = view === 'types'
          ? pair.types.map(function (s) { return ['', s.name, __TYPE_COLORS__[s.name]]; })
              .concat([['abl-key--base', 'no tactile'], ['abl-key--teacher', 'teacher']])
          : pair.levels.map(function (s) { return ['abl-key--' + s.name, s.name]; })
              .concat([['abl-key--base', 'no tactile'], ['abl-key--teacher', 'teacher']]);
        return '<ul class="abl__legend">' + items.map(function (it) {
          const style = it[2] ? ' style="background:' + it[2] + '"' : '';
          return '<li><span class="abl__key ' + it[0] + '"' + style + '></span>' + it[1] + '</li>';
        }).join('') + '</ul>';
      }

      function table(pair) {
        const rows = view === 'types'
          ? pair.types.slice().sort(function (a, b) { return b.final - a.final; })
          : pair.levels;
        const head = '<tr><th scope="col">' + (view === 'types' ? 'Tactile type' : 'Imperfection') + '</th><th scope="col">' + pair.axis + '</th></tr>';
        const body = rows.map(function (r) { return '<tr><th scope="row">' + r.name + '</th><td>' + fmt(r.final) + '</td></tr>'; }).join('');
        const extra = '<tr><th scope="row">no tactile</th><td>' + fmt(pair.baseline) + '</td></tr>'
                    + '<tr><th scope="row">teacher</th><td>' + fmt(pair.teacher) + '</td></tr>';
        return '<table><caption>' + pair.title + '</caption><thead>' + head + '</thead><tbody>' + body + extra + '</tbody></table>';
      }

      function render() {
        const pair = current();
        const W = 720, H = 380;
        const pad = { l: 74, r: 24, t: 14, b: 44 };
        plot.innerHTML = '';
        const svg = el('svg', { viewBox: '0 0 ' + W + ' ' + H, class: 'abl__svg', role: 'img' });
        svg.appendChild(el('title')).textContent = pair.title + ' \\u2014 ' + (view === 'types' ? 'by tactile type' : 'by imperfection');
        (view === 'types' ? drawTypes : drawLevels)(pair, svg, W, H, pad);
        plot.appendChild(svg);
        caption.innerHTML = legend(pair);
        tableBox.innerHTML = table(pair);
      }

      root.addEventListener('click', function (event) {
        const tab = event.target.closest('.abl__tab');
        if (tab) {
          const group = tab.parentElement;
          group.querySelectorAll('.abl__tab').forEach(function (b) { b.setAttribute('aria-selected', String(b === tab)); });
          if (tab.dataset.view) view = tab.dataset.view;
          if (tab.dataset.pair) pairId = tab.dataset.pair;
          render();
          return;
        }
        if (event.target.closest('.abl__toggle')) {
          const shown = toggle.getAttribute('aria-pressed') === 'true';
          toggle.setAttribute('aria-pressed', String(!shown));
          toggle.textContent = shown ? 'Show table' : 'Hide table';
          tableBox.hidden = shown;
        }
      });

      render();
    })();
  </script>
  <!-- END ablation-widget -->
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("results", type=Path)
    parser.add_argument("page", type=Path)
    parser.add_argument("--teachers", type=Path)
    parser.add_argument("--final-iteration", type=int, default=None,
                        help="Embed only runs that reached this iteration (use 2999 for final figures).")
    parser.add_argument("--require-complete", action="store_true",
                        help="Refuse to update the page unless all 39 publication cells are present once.")
    parser.add_argument("--anchor", default="  <!-- ===================== CONTACT AUDIO DEMO ===================== -->")
    args = parser.parse_args()

    teachers = json.loads(args.teachers.read_text()) if args.teachers else {}
    results = json.loads(args.results.read_text())
    if args.require_complete:
        if args.final_iteration is None:
            parser.error("--require-complete also requires --final-iteration")
        require_complete_matrix(results, args.final_iteration)
    data = payload(results, teachers, args.final_iteration)
    section = SECTION.replace("__TYPE_COLORS__", json.dumps(TYPE_COLOR, separators=(",", ":")))
    section = section.replace("__DATA__", json.dumps(data, separators=(",", ":")).replace("'", "&#39;"))

    page = args.page.read_text()
    if BEGIN in page:
        start, tail = page.index(BEGIN), page.index(END) + len(END) + 1
        page = page[:start] + section + page[tail:]
    elif args.anchor in page:
        page = page.replace(args.anchor, section + "\n" + args.anchor, 1)
    else:
        raise SystemExit(f"Anchor not found in {args.page}: {args.anchor!r}. Pass --anchor.")
    args.page.write_text(page)
    print(f"embedded {len(data['pairs'])} hand/task pairs into {args.page}")


if __name__ == "__main__":
    main()
